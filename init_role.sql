DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'museum_app') THEN
        CREATE ROLE museum_app LOGIN PASSWORD '123456789';
    END IF;
END
$$;

GRANT CONNECT ON DATABASE museum_db TO museum_app;
GRANT USAGE ON SCHEMA public TO museum_app;
GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA public TO museum_app;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO museum_app;

ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO museum_app;
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT USAGE, SELECT ON SEQUENCES TO museum_app;